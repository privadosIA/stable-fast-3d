#!/usr/bin/env bash
# Writes tests/fixtures/MANIFEST.md: what the golden run was made with and the sha256 of every fixture (committed or regenerated), as the table
# MusicGen.Core.Testing's FixtureDirectory reads (first cell the file in backticks, one 64-hex cell).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
fixtures="$root/tests/fixtures"
image="${SF3D_IMAGE:-mediaorquestator/model3d:sf3d}"
cd "$fixtures"

{
  echo "# Fixtures of the golden run"
  echo
  echo "Made by \`tools/golden_all.sh\` with the Python reference (Stable Fast 3D, commit \`ff21fc4\`) inside the image \`$image\` (id \`$(docker image inspect "$image" --format '{{.Id}}' 2>/dev/null | cut -c1-19)\`)."
  echo "Nothing here is a weight. \`reference/\` is the fp32 run on the CPU (the numerical truth the parity tests compare with); \`reference-cuda/\` is the run on the card"
  echo "(times, VRAM and the .glb the container makes). Files under \`big/\`, \`pictures/\`, the CUDA run's \`small.safetensors\` and \`160_tets.npz\` are regenerated by the golden run and are not committed;"
  echo "\`tools/verify_manifest.sh\` checks the ones that exist."
  echo
  for r in reference reference-cuda; do
    [ -f "$r/reference.json" ] && { echo "## $r/reference.json"; echo; echo '```json'; cat "$r/reference.json"; echo; echo '```'; echo; }
  done
  echo "## sha256"
  echo
  echo "| file | sha256 | kind |"
  echo "|---|---|---|"
  find . -type f ! -name MANIFEST.md ! -name .gitignore | LC_ALL=C sort | while read -r f; do
    f="${f#./}"
    kind=committed
    case "$f" in */big/*|pictures/*|160_tets.npz|reference-cuda/*/small.safetensors) kind=regenerated ;; esac
    printf '| `%s` | `%s` | %s |\n' "$f" "$(sha256sum "$f" | cut -d' ' -f1)" "$kind"
  done
} > MANIFEST.md
echo "wrote $fixtures/MANIFEST.md"
